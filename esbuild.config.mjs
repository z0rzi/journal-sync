import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';
import { readFileSync } from 'node:fs';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		// `buffer` is bundled: the phone has no Node, and isomorphic-git needs the npm polyfill.
		...builtinModules.filter((m) => m !== 'buffer'),
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	minify: prod,
});

if (prod) {
	await context.rebuild();
	// The phone has no Node: only the desktop-only `fs` may be loaded from Node.
	const nodeModules = [...readFileSync('main.js', 'utf8').matchAll(/require\("([^"]+)"\)/g)]
		.map((m) => m[1])
		.filter((m) => builtinModules.includes(m) && m !== 'fs');
	if (nodeModules.length) {
		console.error(`main.js loads Node modules the phone doesn't have: ${[...new Set(nodeModules)].join(', ')}`);
		process.exit(1);
	}
	process.exit(0);
} else {
	await context.watch();
}
